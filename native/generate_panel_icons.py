"""Encode the polygon-only SVG panel icons as PNG arrays; Python standard library only."""
import pathlib
import struct
import xml.etree.ElementTree as ET
import zlib

root = pathlib.Path(__file__).resolve().parent


def encode(name):
    document = ET.parse(root / 'Resources' / f'{name}.svg').getroot()
    polygons = []
    for element in document:
        if element.tag.rsplit('}', 1)[-1] != 'polygon':
            raise ValueError('Only polygon artwork is supported')
        points = [tuple(map(float, p.split(','))) for p in element.attrib['points'].split()]
        color = bytes.fromhex(element.attrib['fill'].lstrip('#'))
        polygons.append((points, color))

    def inside(points, x, y):
        result = False
        for a, b in zip(points, points[1:] + points[:1]):
            if (a[1] > y) != (b[1] > y) and x < (b[0]-a[0])*(y-a[1])/(b[1]-a[1])+a[0]:
                result = not result
        return result

    size, samples = 48, 4
    pixels = bytearray()
    for y in range(size):
        pixels.append(0)
        for x in range(size):
            rgb, count = [0, 0, 0], 0
            for sy in range(samples):
                for sx in range(samples):
                    color = None
                    for points, fill in polygons:
                        if inside(points, (x+(sx+.5)/samples)/2, (y+(sy+.5)/samples)/2):
                            color = fill
                    if color:
                        count += 1
                        rgb = [a+b for a, b in zip(rgb, color)]
            pixels.extend([*(round(c/count) if count else 0 for c in rgb), round(255*count/samples**2)])

    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind+data))

    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(pixels)) + chunk(b'IEND', b''))


lines = ['// Generated by native/generate_panel_icons.py from the matching SVG resources.', '#pragma once']
for name in ['FreeNestPanelLight', 'FreeNestPanelDark']:
    data = encode(name)
    lines.append(f'inline constexpr unsigned char {name}[]={{')
    lines += ['    '+','.join(f'0x{b:02x}' for b in data[i:i+20])+',' for i in range(0, len(data), 20)]
    lines.append('};')
(root / 'Source' / 'NestPanelIcons.h').write_text('\n'.join(lines)+'\n', encoding='utf-8')
